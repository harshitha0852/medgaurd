import React, { useEffect, useMemo, useState } from 'react';
import { base44 } from '@/api/base44Client';
import {
  ShieldAlert, ShieldCheck, Loader2, RotateCw, AlertTriangle, Pill, Info, BookOpenCheck, ChevronDown, BellRing, Copy,
} from 'lucide-react';
import { useSession } from '@/lib/SessionContext';
import { analyzeMedications } from '@/lib/interactionEngine';
import { notifyCaregivers } from '@/lib/notify';
import { shortDate } from '@/lib/format';
import PageHeader from '@/components/common/PageHeader';
import SeverityBadge from '@/components/common/SeverityBadge';
import StatCard from '@/components/common/StatCard';
import EmptyState from '@/components/common/EmptyState';

const TYPE_LABEL = {
  interaction: 'Drug–drug interaction',
  duplicate: 'Duplicate active ingredient',
  allergy: 'Allergy conflict',
  contraindication: 'Contraindication',
};

export default function DrugConflicts() {
  const { account, activePatient } = useSession();
  const email = activePatient?.account_email;
  const [meds, setMeds] = useState([]);
  const [running, setRunning] = useState(true);
  const [result, setResult] = useState(null);
  const [open, setOpen] = useState({});
  const [savedCheck, setSavedCheck] = useState('');
  const [notified, setNotified] = useState(false);

  const run = async () => {
    if (!email) return;
    setRunning(true);
    setNotified(false);
    try {
      const list = await base44.entities.Medication.filter({ patient_email: email, active: true });
      setMeds(list || []);
      setResult(analyzeMedications(list || [], activePatient));
    } finally {
      setRunning(false);
    }
  };

  useEffect(() => { run(); /* eslint-disable-next-line */ }, [email]);

  const saveCheck = async () => {
    if (!result) return;
    await Promise.all(
      result.alerts.map((a) =>
        base44.entities.InteractionAlert.create({
          patient_email: email,
          type: a.type,
          severity: a.severity,
          title: a.title,
          medicines: a.medicines,
          explanation: a.explanation,
          recommendation: a.recommendation,
          source: a.source,
          checked_at: result.checkedAt,
          acknowledged: false,
        })
      )
    );
    if (result.alerts.length) {
      await notifyCaregivers(email, {
        type: 'interaction',
        title: `${result.counts.high ? 'High-risk' : 'New'} medication alert for ${activePatient?.full_name || 'a patient'}`,
        message: `${result.alerts.length} alert${result.alerts.length > 1 ? 's' : ''} recorded from the interaction check. Please review with the prescriber.`,
        link: '/conflicts',
        severity: result.counts.high ? 'critical' : 'warning',
      });
    }
    setSavedCheck(new Date().toISOString());
    setNotified(true);
  };

  const grouped = useMemo(() => {
    const list = result?.alerts || [];
    return {
      high: list.filter((a) => a.severity === 'high'),
      moderate: list.filter((a) => a.severity === 'moderate'),
      low: list.filter((a) => a.severity === 'low'),
    };
  }, [result]);

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Verified interaction data"
        title="Medication safety check"
        subtitle="Every active medicine is checked against curated clinical interaction references — with duplicate ingredients, allergy conflicts and clear next steps."
        icon={ShieldAlert}
        actions={
          <button onClick={run} disabled={running} className="mg-btn-primary h-11 text-sm">
            {running ? <Loader2 className="h-4 w-4 animate-spin" /> : <RotateCw className="h-4 w-4" />}
            {running ? 'Checking…' : 'Run check again'}
          </button>
        }
      />

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Medicines analysed" value={result?.medicineCount ?? 0} hint="Active prescriptions only" icon={Pill} />
        <StatCard label="High risk" value={grouped.high.length} hint="Needs a doctor or pharmacist" icon={AlertTriangle} tone="red" />
        <StatCard label="Moderate" value={grouped.moderate.length} hint="Monitor and confirm" icon={Info} tone="amber" />
        <StatCard label="Duplicates & allergies" value={(result?.alerts || []).filter((a) => a.type !== 'interaction').length} hint="Same ingredient or recorded allergy" icon={Copy} tone="violet" />
      </div>

      <div className="rounded-2xl border border-primary/15 bg-primary/5 p-4">
        <p className="flex items-start gap-2 text-[12.5px] leading-relaxed text-foreground/80">
          <BookOpenCheck className="mt-0.5 h-4 w-4 shrink-0 text-primary" />
          Results come from a curated clinical reference dataset (Micromedex/BNF-style monographs), never generated by AI.
          MedGuard is an information tool — always confirm changes with your doctor or pharmacist.
        </p>
      </div>

      {running ? (
        <div className="py-16 text-center text-sm text-muted-foreground">Analysing your medicines…</div>
      ) : !result || result.alerts.length === 0 ? (
        <div className="mg-card p-8 text-center">
          <span className="mx-auto mb-3 flex h-14 w-14 items-center justify-center rounded-2xl bg-[hsl(var(--mint))]/12 text-[hsl(var(--mint))]">
            <ShieldCheck className="h-7 w-7" />
          </span>
          <h2 className="text-[19px] font-bold text-foreground">No interactions detected</h2>
          <p className="mx-auto mt-1.5 max-w-md text-[13.5px] text-muted-foreground">
            {result?.medicineCount || 0} active medicines were checked and no known interaction, duplicate ingredient or allergy conflict was found.
          </p>
          {result?.unmatched?.length ? (
            <p className="mx-auto mt-3 max-w-md rounded-xl bg-muted/60 p-3 text-[12px] text-muted-foreground">
              Could not match these medicines to the reference database: {result.unmatched.join(', ')}. Ask your pharmacist to review them.
            </p>
          ) : null}
        </div>
      ) : (
        <div className="space-y-3">
          {result.alerts.map((a) => {
            const isOpen = !!open[a.id];
            return (
              <div key={a.id} className="mg-card overflow-hidden">
                <button onClick={() => setOpen({ ...open, [a.id]: !isOpen })} className="flex w-full items-start gap-3 p-4 text-left sm:p-5">
                  <span className={`mt-0.5 flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${
                    a.severity === 'high' ? 'bg-red-50 text-red-600' : a.severity === 'moderate' ? 'bg-amber-50 text-amber-700' : 'bg-sky-50 text-sky-600'
                  }`}>
                    {a.severity === 'high' ? <AlertTriangle className="h-5 w-5" /> : <Info className="h-5 w-5" />}
                  </span>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <SeverityBadge severity={a.severity} />
                      <span className="mg-chip bg-muted text-muted-foreground">{TYPE_LABEL[a.type] || 'Alert'}</span>
                    </div>
                    <p className="mt-2 text-[15px] font-bold text-foreground">{a.title}</p>
                    <p className="mt-0.5 text-[13px] font-medium text-primary">{a.medicines.join('  +  ')}</p>
                    <p className="mt-1 text-[12.5px] leading-relaxed text-muted-foreground">{a.explanation}</p>
                  </div>
                  <ChevronDown className={`mt-1 h-5 w-5 shrink-0 text-muted-foreground transition ${isOpen ? 'rotate-180' : ''}`} />
                </button>
                {isOpen ? (
                  <div className="border-t border-border bg-muted/30 px-4 py-4 sm:px-5">
                    <div className="grid gap-4 sm:grid-cols-2">
                      <div>
                        <p className="text-[11px] font-bold uppercase tracking-wider text-muted-foreground">What to do</p>
                        <p className="mt-1 text-[13px] leading-relaxed text-foreground">{a.recommendation}</p>
                      </div>
                      <div>
                        <p className="text-[11px] font-bold uppercase tracking-wider text-muted-foreground">Reference</p>
                        <p className="mt-1 text-[12.5px] leading-relaxed text-muted-foreground">{a.source}</p>
                      </div>
                    </div>
                    <p className="mt-3 rounded-xl bg-white p-3 text-[12px] leading-relaxed text-amber-800">
                      This is information, not a diagnosis. Do not stop or change a medicine on your own — speak to the doctor who prescribed it.
                    </p>
                  </div>
                ) : null}
              </div>
            );
          })}
        </div>
      )}

      {result && result.alerts.length > 0 ? (
        <div className="mg-card flex flex-wrap items-center justify-between gap-3 p-4 sm:p-5">
          <div>
            <p className="text-[13.5px] font-semibold text-foreground">Check completed {shortDate(result.checkedAt)}</p>
            <p className="text-[12px] text-muted-foreground">
              {notified ? 'Results saved to history and caregivers notified.' : 'Save this check to the patient history and alert the care team.'}
            </p>
          </div>
          <button onClick={saveCheck} disabled={notified} className="mg-btn-primary h-11 text-sm">
            <BellRing className="h-4 w-4" /> {notified ? 'Saved & notified' : 'Save check & notify caregivers'}
          </button>
        </div>
      ) : null}

      {savedCheck && !notified ? <p className="text-[12px] text-muted-foreground">Last saved {shortDate(savedCheck)}</p> : null}
    </div>
  );
}